import QRCode from "qrcode";
import { delay } from "@/lib/motion";
import styles from "./PhotosQr.module.css";

// Page 8: "Share the moments". A QR code guests scan at the wedding to add
// their photos to the couple's album. The QR is drawn on the server as SVG
// at build time, so the guest's phone downloads no QR library at all.
type Props = {
  label: string; // "On the day"
  title: string; // "Share the moments"
  text: string;
  url: string; // the album link the QR opens
  qrLabel: string; // for screen readers
};

export async function PhotosQr({ label, title, text, url, qrLabel }: Props) {
  const svg = await QRCode.toString(url, {
    type: "svg",
    margin: 0,
    errorCorrectionLevel: "M",
    color: { dark: "#36332B", light: "#FFFFFF" },
  });

  return (
    <section className="paper">
      <p className="caps" data-a="up">
        {label}
      </p>
      <p className="scr" style={{ fontSize: "14cqw", ...delay(0.1) }} data-a="soft">
        {title}
      </p>
      <p className="body it" data-a="up" style={delay(0.15)}>
        {text}
      </p>
      <div
        className={styles.qr}
        data-a="up"
        style={delay(0.3)}
        role="img"
        aria-label={qrLabel}
        // Generated by the qrcode library from our own URL, not user input.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
    </section>
  );
}
