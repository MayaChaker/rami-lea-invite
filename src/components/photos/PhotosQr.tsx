import QRCode from "qrcode";
import { delay } from "@/lib/motion";
import styles from "./PhotosQr.module.css";

// The last page: "Thank you", and a QR code guests scan at the wedding to add
// their photos to the couple's album. Ivory paper with lace in the top corner
// and roses at the bottom. The QR is drawn on the server as SVG at build time,
// so the guest's phone downloads no QR library at all.
type Props = {
  title: string; // "Thank you"
  label: string; // "For being part of our story"
  text: string; // "Scan to share your photos of the day"
  url: string; // the album link the QR opens
  qrLabel: string; // for screen readers
};

export async function PhotosQr({ title, label, text, url, qrLabel }: Props) {
  const svg = await QRCode.toString(url, {
    type: "svg",
    margin: 0,
    errorCorrectionLevel: "M",
    color: { dark: "#36332B", light: "#FBF8F3" },
  });

  return (
    <section className="paper">
      <span className="deco lace tr" style={{ width: "66cqw" }} aria-hidden="true" />
      <span className="deco roses bl" style={{ width: "56cqw" }} aria-hidden="true" />

      <h2 className="title" data-a="up">
        {title}
      </h2>
      <span className="divider" data-a="up" style={delay(0.1)} aria-hidden="true">
        <i />
      </span>
      <p className="caps" data-a="up" style={delay(0.15)}>
        {label}
      </p>
      <div
        className={styles.qr}
        data-a="up"
        style={delay(0.3)}
        role="img"
        aria-label={qrLabel}
        // Generated by the qrcode library from our own URL, not user input.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <p className={`caps ${styles.scan}`} data-a="up" style={delay(0.4)}>
        {text}
      </p>
    </section>
  );
}
